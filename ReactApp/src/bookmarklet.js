// Bookmarklets: the extension-free way to fill the See Tickets registration
// form (2026-09-16; hybrid live-fetch added 2026-09-17).
//
// Why: Lightning Autofill (the renamed "AutoFill Options") caps its free plan
// at 10 profile executions a day, so anyone who tests or reloads on sale
// morning can be locked out at the moment it matters. A bookmarklet is a
// bookmark whose address is a snippet of JavaScript; click it on the
// registration page and it fills the boxes. No extension, no account, no
// quota, and it works in Chrome, Edge, Firefox and Safari.
//
// The data comes from the SAME autofill files the extension uses
// (GET /files/{filename}, AutoFill's CSV export format, generated by
// Common/BusWankers.cs), parsed here into groups. So nothing changes on the
// backend and the extension path keeps working for anyone who wants it.
//
// Data freshness - the hybrid design (2026-09-17): a bookmarklet's data used
// to be baked in once, at generation time, and then sat unchanged in the
// user's real browser bookmarks for as long as they kept it - stale the
// moment the underlying spreadsheet was re-ingested with a correction. Now
// every bookmarklet ALSO carries the URL of its sale's live, structured group
// data (GET /files/{filename}/groups - see UploadServiceController.
// DownloadGroups and AutofillStore.SaveGroupsAsync), and on click it tries
// that first: a short, timed fetch, cross-origin, from whatever page happens
// to be open (the actual registration page, on a domain this app has no way
// to know in advance - the service's CORS policy already allows any origin,
// see Program.cs). Only if that fails - offline, the request times out, the
// registration page's own CSP blocks it, nothing's been re-ingested since the
// bookmark was made - does it fall back to the data embedded at generation
// time, exactly as before. So a bookmark made in August and clicked in
// September gets August's fallback only in the worst case; normally it gets
// whatever is live right now. There is deliberately no offline mode at all
// for this fetch beyond that one fallback: no retry loop, no long timeout -
// sale mornings have a 10-minute registration window, and a bookmarklet that
// might hang on a dead network is worse than one that gives up in four
// seconds and uses what it already has.
//
// The fill logic lives in FILL_SOURCE as a string, because it has to be
// embedded verbatim in the bookmarklet URL. runFillOnThisPage() runs the very
// same source against our own Test Form, so what's tested is what ships -
// live fetch included, since the Test Form is served from this same origin
// and so is a genuine (same-origin) rehearsal of the live-fetch path, not
// just the fallback.

// ---------------------------------------------------------------------------
// Parsing the AutoFill CSV
// ---------------------------------------------------------------------------

// Minimal CSV line splitter: fields may be double-quoted (our generator
// quotes the rule name/value/site); no embedded newlines are ever produced.
function splitCsvLine(line) {
  const out = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') { cur += '"'; i++; } else { inQuotes = false; }
      } else {
        cur += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      out.push(cur);
      cur = '';
    } else {
      cur += ch;
    }
  }
  out.push(cur);
  return out.map((s) => s.trim());
}

// "Group-A" -> "A", "Coach Group-A" -> "A", "Group-1" -> "1"; anything else
// as-is. No "^" anchor: the backend now prefixes the profile Name with the
// sale's own short label (see UploadServiceController.SaleFolderLabelFor /
// GenerateAutofillTextFromGroups, 2026-09-18) so two sales that both happen
// to have a "Group A" are never ambiguous once imported into AutoFill
// Options/Lightning Autofill - but the RAW label recovered here still has
// to be just the bare letter, because it's matched against the live groups
// JSON's own (never-prefixed) label field - see liveMembersFor below and
// ToGroupsDocument on the backend.
const groupLabelFromProfileName = (name) => {
  const m = /Group-(.+)$/i.exec(name || '');
  return m ? m[1] : (name || '');
};

// "Coach Group A" - the sale-qualified group name shown everywhere a group
// is named to a person: bookmark titles, their on-page confirmation
// banners, the whole-sale bookmarklet's tap-to-choose picker, and the
// Documentation/Groups tabs' group headings (2026-09-18) - so two sales
// that both happen to have a "Group A" (e.g. Coach and General) are never
// ambiguous. saleFolderLabel is SALE_INFO[...].folderLabel (see
// saleInfo.js) - "Coach", "General", "Coach Resale", "General Resale";
// falls back to a bare "Group A" if one was never known.
export const groupDisplayLabel = (saleFolderLabel, label) =>
  saleFolderLabel ? `${saleFolderLabel} Group ${label}` : `Group ${label}`;

// Parses an autofill file into groups:
//   [{ code: 'c1', label: 'A', name: 'Group-A', members: [{ registrationId, postCode }] }]
// Members are in slot order; padding slots (blank reg number AND postcode)
// are dropped, so members.length is the real group size.
export function parseAutofillCsv(text) {
  const lines = String(text || '').split(/\r?\n/);
  let section = null; // 'profiles' | 'rules' | 'options'
  const profiles = new Map(); // code -> { code, label, name, slots: Map<slot, {registrationId, postCode}> }
  const order = [];

  for (const raw of lines) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('### AUTOFILL PROFILES')) { section = 'profiles'; continue; }
    if (line.startsWith('### AUTOFILL RULES')) { section = 'rules'; continue; }
    if (line.startsWith('### AUTOFILL OPTIONS')) { section = 'options'; continue; }

    const f = splitCsvLine(line);
    if (section === 'profiles') {
      if (/^profile id$/i.test(f[0] || '')) continue; // header row
      const code = f[0];
      if (!/^c\d+$/i.test(code)) continue;
      const name = f[1] || code;
      profiles.set(code, { code, name, label: groupLabelFromProfileName(name), slots: new Map() });
      order.push(code);
    } else if (section === 'rules') {
      if (/^rule id$/i.test(f[0] || '')) continue; // header row
      // Rule ID, Type, Name, Value, Site, Mode, Profile
      const fieldName = f[2] || '';
      const value = f[3] || '';
      const code = f[6] || '';
      const m = /registrations[^0-9]*(\d+)[^a-z]*(registrationid|postcode)/i.exec(fieldName);
      if (!m) continue;
      const profile = profiles.get(code);
      if (!profile) continue;
      const slot = Number(m[1]);
      const entry = profile.slots.get(slot) || { registrationId: '', postCode: '' };
      if (m[2].toLowerCase() === 'registrationid') entry.registrationId = value.trim();
      else entry.postCode = value.trim();
      profile.slots.set(slot, entry);
    }
  }

  return order.map((code) => {
    const p = profiles.get(code);
    const members = [...p.slots.entries()]
      .sort((a, b) => a[0] - b[0])
      .map(([, e]) => e)
      .filter((e) => e.registrationId || e.postCode);
    return { code: p.code, name: p.name, label: p.label, members };
  });
}

