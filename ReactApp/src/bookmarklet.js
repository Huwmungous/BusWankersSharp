// Runs with four variables in scope: M (the embedded fallback - array of
// [registrationId, postCode], in slot order), G (the raw group label, e.g.
// "A"), U (the absolute URL of this sale's live group data, or '' if
// none was available when the bookmark was generated), and S (the sale's
// own short display label, e.g. "Coach" - see groupDisplayLabel above; ''
// if none was known, in which case the confirmation banner below just says
// "Group A" rather than "Coach Group A"). Deliberately
// old-school JS (no arrow functions, template literals, let/const) so it
// runs on any browser someone might be using on the day - fetch/Promise
// themselves are assumed available (every browser released since 2016 has
// them; a browser old enough not to would already be unable to load the
// registration page itself), but everything here uses plain functions and
// .then/.catch rather than async/await. Keep it self-contained - it cannot
// reference anything from this module.
//
// Matching strategy for the page's input boxes, in order:
//   1. inputs whose id OR name matches registrations…N…RegistrationId /
//      …Postcode (case-insensitive; covers registrations_0__RegistrationId,
//      registrations[0].RegistrationId and reasonable variants);
//   2. failing that, inputs by class (See Tickets uses .numeric / .postcode)
//      or by id containing "egistration" / "ostcode", paired up in order.
// Values are written through the native setter and followed by input/change
// events, so plain, jQuery-validated AND React forms all see a real edit.
//
// Data source, in order: a live fetch of U (aborted after 4 seconds so a
// dead network can't stall someone in the registration window), falling back
// to M if U is empty, the fetch fails, times out, the response isn't OK, or
// it doesn't contain this group's label. Either way the confirmation banner
// says which one was actually used ("live data" / "offline backup data"),
// so nobody has to guess.
export const FILL_SOURCE = `
(function(){
  function nat(el, v) {
    var proto = Object.getPrototypeOf(el);
    var d = Object.getOwnPropertyDescriptor(proto, 'value') || Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value');
    if (d && d.set) { d.set.call(el, v); } else { el.value = v; }
    try { el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); }
    catch (e) { var ev = document.createEvent('HTMLEvents'); ev.initEvent('change', true, false); el.dispatchEvent(ev); }
  }
  function find(i, kind) {
    var re = new RegExp('registrations[^0-9]*' + i + '[^a-z0-9]+' + kind + '$', 'i');
    var ins = document.querySelectorAll('input');
    for (var k = 0; k < ins.length; k++) {
      var e = ins[k];
      if (re.test(e.id || '') || re.test(e.name || '')) return e;
    }
    return null;
  }
  var slots = [];
  for (var i = 0; i < 20; i++) {
    var r = find(i, 'registrationid'), p = find(i, 'postcode');
    if (!r && !p) break;
    slots.push([r, p]);
  }
  if (!slots.length) {
    var regs = document.querySelectorAll('input.numeric, input[id*="egistration"], input[name*="egistration"]');
    var posts = document.querySelectorAll('input.postcode, input[id*="ostcode"], input[name*="ostcode"]');
    for (var j = 0; j < Math.max(regs.length, posts.length); j++) slots.push([regs[j] || null, posts[j] || null]);
  }
  if (!slots.length) {
    alert('Bus Wankers: no registration boxes found on this page. Are you on the Glastonbury registration page?');
    return;
  }

  function showBanner(msg, isProblem) {
    try {
      var old = document.getElementById('bw-fill-banner'); if (old) old.parentNode.removeChild(old);
      var b = document.createElement('div');
      b.id = 'bw-fill-banner';
      b.textContent = msg + ' (click to dismiss)';
      b.setAttribute('style', 'position:fixed;top:0;left:0;right:0;z-index:2147483647;background:' + (isProblem ? '#b3261e' : '#1a7f37') + ';color:#fff;font:15px/1.4 Arial,sans-serif;padding:12px 16px;text-align:center;box-shadow:0 2px 6px rgba(0,0,0,.3);cursor:pointer');
      b.onclick = function () { if (b.parentNode) b.parentNode.removeChild(b); };
      document.body.appendChild(b);
      setTimeout(function () { if (b.parentNode) b.parentNode.removeChild(b); }, 15000);
    } catch (e) { alert(msg); }
  }

  function fillWithData(members, source) {
    var filled = 0;
    for (var s = 0; s < slots.length; s++) {
      var m = members[s] || ['', ''];
      if (slots[s][0]) nat(slots[s][0], m[0]);
      if (slots[s][1]) nat(slots[s][1], m[1]);
      if (m[0] && slots[s][0]) filled++;
    }
    var missing = members.length > slots.length ? members.slice(slots.length) : [];
    var groupName = (S ? S + ' Group ' : 'Group ') + G;
    var msg = 'Bus Wankers - ' + groupName + ' (' + source + '): filled ' + filled + ' of ' + members.length + ' people.';
    if (missing.length) {
      msg += ' This page only has ' + slots.length + ' slots, so NOT entered: ' + missing.map(function (x) { return x[0]; }).join(', ') + '.';
    }
    msg += ' Check the boxes, then click Proceed.';
    showBanner(msg, missing.length > 0);
  }

  function liveMembersFor(body) {
    var groups = (body && body.groups) || [];
    for (var i = 0; i < groups.length; i++) {
      if (String(groups[i].label) === String(G) && groups[i].members && groups[i].members.length) {
        var out = [];
        for (var j = 0; j < groups[i].members.length; j++) {
          var mem = groups[i].members[j];
          out.push([String(mem.registrationId || ''), String(mem.postCode || '').replace(/\\s+/g, '').toUpperCase()]);
        }
        return out;
      }
    }
    return null;
  }

  if (!U || !window.fetch) {
    fillWithData(M, 'offline backup data');
    return;
  }

  var settled = false;
  var timer = setTimeout(function () {
    if (settled) return;
    settled = true;
    fillWithData(M, 'offline backup data – live check timed out');
  }, 4000);

  fetch(U, { cache: 'no-store', mode: 'cors', credentials: 'omit' }).then(function (r) {
    if (!r.ok) throw new Error('bad status');
    return r.json();
  }).then(function (body) {
    if (settled) return;
    var live = liveMembersFor(body);
    if (!live) throw new Error('group not present live');
    settled = true;
    clearTimeout(timer);
    fillWithData(live, 'live data');
  }).catch(function () {
    if (settled) return;
    settled = true;
    clearTimeout(timer);
    fillWithData(M, 'offline backup data');
  });
})();
`;

// Postcodes go in upper case with no spaces - that's how the See Tickets
// form displays them (text-transform: uppercase) and how the roster has
// them; it also avoids a trailing-space mismatch against the registration.
const normalisePostcode = (s) => String(s || '').replace(/\s+/g, '').toUpperCase();

const membersToTuples = (members) =>
  members.map((m) => [String(m.registrationId || '').trim(), normalisePostcode(m.postCode)]);

